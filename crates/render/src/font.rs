#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn characters_are_distinct_and_lower_case_draws_capitals() {
        let set: Vec<char> = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_.,:()/+#".chars().collect();
        for (i, a) in set.iter().enumerate() {
            assert!(rows(*a).iter().all(|r| *r < 0x20), "{a}");
            for b in set.iter().skip(i + 1) {
                assert_ne!(rows(*a), rows(*b), "{a} and {b}");
            }
        }
        assert_eq!(rows('r'), rows('R'));
        assert_eq!(rows('é'), rows('?'));
        assert!(on('L', 0, 6) && !on('L', 4, 0) && !on('L', 9, 0) && !on('L', 0, 9));
    }

    #[test]
    fn captions_have_lower_case_and_the_marks_of_units() {
        let set: Vec<char> = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_.,:()/+#=°[]·µ²³%×!'".chars().collect();
        for (i, a) in set.iter().enumerate() {
            assert!(cased(*a).iter().all(|r| *r < 0x20), "{a}");
            for b in set.iter().skip(i + 1) {
                assert_ne!(cased(*a), cased(*b), "{a} and {b}");
            }
        }
        assert_eq!(cased('R'), rows('R'));
        assert_eq!(cased('é'), rows('?'));
    }
}
