/// The edge neighbours of every node, ascending, from the elements around it (in parallel).
fn edge_neighbours(around: &[Vec<u32>], hexes: &[[u32; 8]]) -> Vec<Vec<u32>> {
    fieldcraft_parallel::map_grained(around.len(), NODE_GRAIN, |v| {
        let mut e = Vec::with_capacity(24);
        for hex in around.get(v).into_iter().flatten().filter_map(|&h| hexes.get(h as usize)) {
            for (k, bits) in CORNERS.iter().enumerate() {
                if hex[k] as usize != v {
                    continue;
                }
                for d in 0..3 {
                    let mut b = *bits;
                    b[d] = 1 - b[d];
                    e.push(hex[corner_at(b)]);
                }
            }
        }
        e.sort_unstable();
        e.dedup();
        e
    })
}

/// The smallest scaled Jacobian and the largest edge ratio of a mesh.
fn mesh_quality(x: &[P], hexes: &[[u32; 8]]) -> Local {
    let each = fieldcraft_parallel::map_grained(hexes.len(), HEX_GRAIN, |e| {
        hexes.get(e).map_or((f64::INFINITY, 1.0), |hex| {
            let c = hex.map(|q| at(x, q));
            (hex_scaled_jacobian(&c), hex_edge_ratio(&c))
        })
    });
    let mut l = Local { sj: f64::INFINITY, ratio: 1.0 };
    for (sj, ratio) in each {
        l.sj = l.sj.min(sj);
        l.ratio = l.ratio.max(ratio);
    }
    l
}

/// A grid's smallest and mean scaled Jacobian, to pick the best grid the sweeps passed through.
#[derive(Debug, Clone, Copy)]
struct SweepScore {
    min: f64,
    mean: f64,
}

impl SweepScore {
    /// A larger smallest scaled Jacobian, or the same one (to rounding) with a larger mean.
    /// `tie`: smallest scaled Jacobians this close count as equal.
    fn better_than(self, other: SweepScore, tie: f64) -> bool {
        if (self.min - other.min).abs() > tie { self.min > other.min } else { self.mean > other.mean + SCORE_TIE }
    }
}

/// Two smallest scaled Jacobians this close count as equal.
const SCORE_TIE: f64 = 1e-9; // unit-factors: a difference of scaled Jacobians

/// The lift from the best sweep grid replaces the lift from where the sweeps stopped only when
/// it raises the smallest scaled Jacobian by more than this: an earlier sweep grid is less smooth
/// (its lines kink), which a gain in the third decimal does not pay for; within it the higher
/// mean wins.
const START_TIE: f64 = 0.01;

fn sweep_score(x: &[P], hexes: &[[u32; 8]]) -> SweepScore {
    let (mut min, mut sum) = (f64::INFINITY, 0.0);
    for sj in scaled_jacobians(x, hexes) {
        min = min.min(sj);
        sum += sj;
    }
    SweepScore { min, mean: if hexes.is_empty() { 0.0 } else { sum / hexes.len() as f64 } }
}

/// How to smooth: the method, at most `iterations` sweeps, stopping when no node moves more than
/// `tol`, the nodes moved in `order`.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Run {
    pub method: Smoothing,
    pub iterations: usize,
    pub tol: f64,
    pub order: Order,
}

/// Smooth in place ([`Run`]): at most `iterations` sweeps, stopping when no node moves more than `tol`.
///
/// The sweeps let a move take an element down to [`SWEEP_FLOOR`] (a sheared block straightens
/// only when its nodes move together, and a node-by-node rule that never lowers a poor element
/// stalls halfway), and the compass search then lifts the worst elements. When that does not
/// hold the grid it started from (a smaller smallest scaled Jacobian, or a larger edge ratio
/// past [`EDGE_RATIO_CEILING`]), smoothing starts again with sweeps that never lower an element
/// below [`QUALITY_FLOOR`]; and when neither holds it, the grid stays as it was. So smoothing never
/// leaves the mesh worse than it found it (a regular grid of graded layers, which Laplace's
/// equation would even out, is kept).
pub(crate) fn smooth(m: Mesh, g: &dyn Geometry, targets: &[Vec<u32>], run: Run) -> Result<SmoothReport> {
    let start = m.nodes.clone();
    let before = mesh_quality(&start, m.hexes);
    let mut m = m;
    let mut report = pass(&mut m, g, targets, run, SWEEP_FLOOR)?;
    if mesh_quality(m.nodes, m.hexes).holds(before) {
        return Ok(report);
    }
    m.nodes.clone_from(&start);
    let strict = pass(&mut m, g, targets, run, QUALITY_FLOOR)?;
    report = SmoothReport { iterations: report.iterations + strict.iterations, refused: report.refused + strict.refused };
    if !mesh_quality(m.nodes, m.hexes).holds(before) {
        *m.nodes = start;
    }
    Ok(report)
}

/// One smoothing run; sweep moves keep every element at or above the lower of its scaled
/// Jacobian before and `sweep_floor`.
fn pass(m: &mut Mesh, g: &dyn Geometry, targets: &[Vec<u32>], run: Run, sweep_floor: f64) -> Result<SmoothReport> {
    let Run { method, iterations, tol, order } = run;
    let n = m.nodes.len();
    let mut around: Vec<Vec<u32>> = vec![Vec::new(); n];
    for (h, hex) in m.hexes.iter().enumerate() {
        for &v in hex {
            if let Some(a) = around.get_mut(v as usize) {
                a.push(h as u32);
            }
        }
    }
    // Edge neighbours (all) and boundary neighbours (along boundary quads).
    let edges = edge_neighbours(&around, m.hexes);
    let mut along_boundary: BTreeMap<u32, BTreeSet<u32>> = BTreeMap::new();
    for q in m.boundary {
        for i in 0..4 {
            let (a, b) = (q[i], q[(i + 1) % 4]);
            along_boundary.entry(a).or_default().insert(b);
            along_boundary.entry(b).or_default().insert(a);
        }
    }
    let cons = |v: u32| m.constraint.get(v as usize).copied().unwrap_or(Constraint::Free);
    let is_held = |v: u32| m.held.get(v as usize).copied().unwrap_or(false);
    let stencils: Vec<Option<Stencil>> = if matches!(method, Smoothing::Elliptic | Smoothing::EllipticControlled) {
        let nodes: &[P] = m.nodes;
        fieldcraft_parallel::map_grained(n, NODE_GRAIN, |i| {
            let v = i as u32;
            if cons(v) != Constraint::Free {
                return None;
            }
            let mut s = around.get(i).and_then(|a| stencil(v, a, m.hexes));
            if let (Some(st), Smoothing::EllipticControlled) = (s.as_mut(), method) {
                let p = at(nodes, v);
                for d in 0..3 {
                    let (mi, pl) = (at(nodes, st.nb[d][0]), at(nodes, st.nb[d][1]));
                    let xi = scale(sub(pl, mi), 0.5);
                    let xii = sub(add(pl, mi), scale(p, 2.0));
                    let l2 = dot(xi, xi);
                    st.control[d] = if l2 > 0.0 { (-dot(xi, xii) / l2).clamp(-MAX_CONTROL, MAX_CONTROL) } else { 0.0 };
                }
            }
            s
        })
    } else {
        vec![None; n]
    };
    let hexes = m.hexes;
    let quality = |x: &[P], v: u32| -> Local {
        let mut l = Local { sj: f64::INFINITY, ratio: 1.0 };
        for hex in around.get(v as usize).into_iter().flatten().filter_map(|&h| hexes.get(h as usize)) {
            let c = hex.map(|q| at(x, q));
            l.sj = l.sj.min(hex_scaled_jacobian(&c));
            l.ratio = l.ratio.max(hex_edge_ratio(&c));
        }
        l
    };
    let mut report = SmoothReport { iterations: 0, refused: 0 };
    if method == Smoothing::None {
        return Ok(report);
    }
    let ptol = PROJECTION * tol;
    // The sweeps do not raise the smallest scaled Jacobian monotonically (a move may take an
    // element down to the sweep floor), so where they stop decides the result; keep the best grid
    // seen (smallest scaled Jacobian, then the mean) and lift the worst elements from that.
    let mut best = (sweep_score(m.nodes, hexes), m.nodes.clone());
    let sweep = Sweep {
        hexes,
        around: &around,
        constraint: m.constraint,
        held: m.held,
        stencils: &stencils,
        edges: &edges,
        along_boundary: &along_boundary,
        g,
        targets,
        ptol,
        floor: sweep_floor,
    };
    let classes = if order == Order::Sequential { Vec::new() } else { colour_classes(&sweep, n) };
    // On a device: each class split into the free nodes the device moves and the rest, moved here.
    let mut device = None;
    let mut split: Vec<(Vec<u32>, Vec<u32>)> = Vec::new();
    if order == Order::Device {
        let factory = sweep_device_factory().ok_or_else(|| {
            Error::Unsupported("this build has no GPU smoothing (no sweep device is registered): smooth with the `cpu` or `coloured` backend".into())
        })?;
        let mut device_classes = Vec::with_capacity(classes.len());
        for class in &classes {
            let (free, rest): (Vec<u32>, Vec<u32>) = class.iter().partition(|&&v| sweep.cons(v) == Constraint::Free);
            let rule = |v: u32| match stencils.get(v as usize).copied().flatten() {
                Some(s) => Rule::Winslow { nb: s.nb, diag: s.diag, control: s.control },
                None => Rule::Mean(edges.get(v as usize).cloned().unwrap_or_default()),
            };
            device_classes.push(free.iter().map(|&v| DeviceNode { node: v, rule: rule(v) }).collect());
            split.push((free, rest));
        }
        let mesh = SweepMesh { nodes: m.nodes, hexes, around: &around, classes: device_classes, floor: sweep_floor, min_move: ptol };
        device = Some(factory(&mesh)?);
    }
    for it in 0..iterations {
        report.iterations = it + 1;
        let mut moved = 0.0f64;
        let mut apply = |nodes: &mut Vec<P>, v: u32, mv: Move| match mv {
            Move::Stay => {}
            Move::To(x) => {
                if let Some(slot) = nodes.get_mut(v as usize) {
                    moved = moved.max(dist(x, *slot));
                    *slot = x;
                }
            }
            Move::Refused => report.refused += 1,
        };
        match order {
            Order::Sequential => {
                for v in 0..n as u32 {
                    let mv = sweep.step(m.nodes, v);
                    apply(m.nodes, v, mv);
                }
            }
            Order::Coloured => {
                for class in &classes {
                    let nodes: &[P] = m.nodes;
                    let moves =
                        fieldcraft_parallel::map_grained(class.len(), NODE_GRAIN, |i| class.get(i).map_or(Move::Stay, |&v| sweep.step(nodes, v)));
                    for (&v, mv) in class.iter().zip(moves) {
                        apply(m.nodes, v, mv);
                    }
                }
            }
            Order::Device => {
                let Some(dev) = device.as_mut() else { return Err(Error::Failed("the sweep device is missing".into())) };
                for (k, (free, rest)) in split.iter().enumerate() {
                    // The device moves the free nodes of the class while the host moves the rest,
                    // both from the grid as it was before the class.
                    let moves = dev.sweep(k)?;
                    if moves.len() != free.len() {
                        return Err(Error::Failed(format!("{} moved {} of {} nodes", dev.name(), moves.len(), free.len())));
                    }
                    let nodes: &[P] = m.nodes;
                    let here =
                        fieldcraft_parallel::map_grained(rest.len(), NODE_GRAIN, |i| rest.get(i).map_or(Move::Stay, |&v| sweep.step(nodes, v)));
                    for (&v, mv) in free.iter().zip(moves) {
                        apply(m.nodes, v, mv);
                    }
                    let mut placed = Vec::new();
                    for (&v, mv) in rest.iter().zip(here) {
                        if let Move::To(x) = mv {
                            placed.push((v, x));
                        }
                        apply(m.nodes, v, mv);
                    }
                    dev.set(&placed)?;
                }
            }
        }
        let score = sweep_score(m.nodes, hexes);
        if score.better_than(best.0, SCORE_TIE) {
            best = (score, m.nodes.clone());
        }
        if moved <= tol {
            break;
        }
    }
    // Where the sweeps stopped and the best grid they passed through each go through the lift
    // and the straightening; the better result is kept (the lift can raise an element the best
    // sweep grid left low, so neither start always wins).
    let end = m.nodes.clone();
    let mut starts = vec![end];
    if best.1 != starts[0] {
        starts.push(best.1);
    }
    let mut finished: Option<(SweepScore, Local, Vec<P>)> = None;
    let surface_classes: Vec<Vec<u32>> = classes.iter().map(|c| c.iter().copied().filter(|&v| sweep.on_surface(v)).collect()).collect();
    for start in starts {
        *m.nodes = start;
        // The worst elements: each of their nodes searched for the place that raises the smallest
        // scaled Jacobian around it (a compass search, the optimization-based smoothing of L. A.
        // Freitag and C. Ollivier-Gooch, *Tetrahedral mesh improvement using swapping and smoothing*,
        // IJNME 40:3979–4002, 1997, on Knupp's hexahedral metric), boundary nodes kept on their
        // targets.
        for _ in 0..OPTIMIZE_ROUNDS {
            let mut poor: Vec<u32> = m
                .hexes
                .iter()
                .zip(scaled_jacobians(m.nodes, m.hexes))
                .filter(|(_, sj)| *sj < LIFT_BELOW)
                .flat_map(|(h, _)| h.iter().copied())
                .collect();
            poor.sort_unstable();
            poor.dedup();
            if poor.is_empty() {
                break;
            }
            let mut improved = false;
            for &v in &poor {
                let c = cons(v);
                if matches!(c, Constraint::Corner(..)) || is_held(v) {
                    continue;
                }
                let p = at(m.nodes, v);
                let reach = edges.get(v as usize).map_or(0.0, |e| e.iter().map(|&w| dist(at(m.nodes, w), p)).fold(f64::INFINITY, f64::min));
                if !(reach > 0.0 && reach.is_finite()) {
                    continue;
                }
                let start_quality = quality(m.nodes, v);
                let mut best = (start_quality.sj, p);
                let mut h = 0.25 * reach;
                for _ in 0..6 {
                    let start = best.1;
                    for dir in COMPASS {
                        let x = place(g, targets, c, add(start, scale(dir, h)), ptol);
                        if let Some(slot) = m.nodes.get_mut(v as usize) {
                            *slot = x;
                        }
                        let qx = quality(m.nodes, v);
                        if qx.sj > best.0 + SCORE_TIE && qx.keeps(start_quality) {
                            best = (qx.sj, x);
                        }
                    }
                    if best.1 == start {
                        h *= 0.5;
                    }
                }
                if let Some(slot) = m.nodes.get_mut(v as usize) {
                    *slot = best.1;
                }
                improved |= best.1 != p;
            }
            if !improved {
                break;
            }
        }
        // The search moves boundary nodes one at a time, each to its own best place, which leaves the
        // grid lines on a face zigzagging from node to node. Straighten them: each surface node back
        // toward the mean of its neighbours on the surface, as far as no element round it falls below
        // the lower of its own value and the mesh's smallest after the search (so the mesh's worst
        // element is no worse for it).
        let floor = scaled_jacobians(m.nodes, hexes).into_iter().fold(f64::INFINITY, f64::min);
        for _ in 0..STRAIGHTEN_SWEEPS {
            let mut moved = false;
            let mut apply = |nodes: &mut Vec<P>, v: u32, mv: Move| {
                if let (Move::To(x), Some(slot)) = (mv, nodes.get_mut(v as usize)) {
                    *slot = x;
                    moved = true;
                }
            };
            if order == Order::Sequential {
                for v in (0..n as u32).filter(|&v| sweep.on_surface(v)) {
                    let mv = sweep.straighten(m.nodes, v, floor);
                    apply(m.nodes, v, mv);
                }
            } else {
                // Colour by colour, as the sweeps went.
                for surface in &surface_classes {
                    let nodes: &[P] = m.nodes;
                    let moves = fieldcraft_parallel::map_grained(surface.len(), SURFACE_GRAIN, |i| {
                        surface.get(i).map_or(Move::Stay, |&v| sweep.straighten(nodes, v, floor))
                    });
                    for (&v, mv) in surface.iter().zip(moves) {
                        apply(m.nodes, v, mv);
                    }
                }
            }
            if !moved {
                break;
            }
        }
        let (score, local) = (sweep_score(m.nodes, hexes), mesh_quality(m.nodes, hexes));
        let better = finished.as_ref().is_none_or(|(s, l, _)| score.better_than(*s, START_TIE) && local.ratio <= l.ratio.max(EDGE_RATIO_CEILING));
        if better {
            finished = Some((score, local, m.nodes.clone()));
        }
    }
    if let Some((_, _, nodes)) = finished {
        *m.nodes = nodes;
    }
    Ok(report)
}
