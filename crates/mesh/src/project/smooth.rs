//! Smoothing of a projected block mesh with its boundary held on the geometry.
//!
//! Interior nodes with the regular neighbourhood of a structured grid (eight hexahedra, six
//! edge neighbours in three opposite pairs) move by the elliptic (Winslow) grid equations,
//! `Σ g^{ij} x_{ξ^i ξ^j} + Σ g^{ii} φ_i x_{ξ^i} = 0` (A. M. Winslow, *Numerical solution of the
//! quasilinear Poisson equation in a nonuniform triangle mesh*, J. Comput. Phys. 2:149–172, 1967;
//! the three-dimensional form and its discretisation in J. F. Thompson, Z. U. A. Warsi,
//! C. W. Mastin, *Numerical Grid Generation*, North-Holland 1985, ch. 6), solved point by point
//! with central differences in the node's own stencil. The optional control functions `φ_i`
//! follow P. D. Thomas and J. F. Middlecoff, *Direct control of the grid point distribution in
//! meshes generated by elliptic equations*, AIAA J. 18(6):652–656, 1980, in their
//! one-dimensional form `φ = −x_ξ·x_ξξ / |x_ξ|²`, evaluated on the algebraic (transfinite) grid
//! at every node, so the smoothed grid keeps that grid's spacing along each line. Irregular nodes
//! (where three, five or more blocks meet) take the mean of their neighbours (Laplace).
//!
//! Boundary nodes move along their surface or curve: the mean of their boundary neighbours,
//! projected back. Block vertices on three targets stay put.
//!
//! Every move is checked: it is kept only when the smallest scaled Jacobian of the elements
//! around the node stays at or above the lower of its value before and [`QUALITY_FLOOR`], and
//! their largest edge ratio at or below the higher of its value before and
//! [`EDGE_RATIO_CEILING`], so smoothing never makes a good element bad nor a bad one worse. The
//! scaled Jacobian alone does not see an edge shrinking to nothing (its corners stay square while
//! the element flattens into a sliver), so both are guarded.

